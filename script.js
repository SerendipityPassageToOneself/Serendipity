const originalHTML = new Map();

function applyLanguage(lang) {
  const dict = translations[lang];

  document.title = dict.title;
  document.documentElement.lang = lang === "ja" ? "ja" : "en";
  document.body.classList.toggle("japanese", lang === "ja");

  for (const [selector, value] of Object.entries(dict)) {
    if (selector === "title" || selector === "nav") continue;
    const nodes = document.querySelectorAll(selector);
    nodes.forEach((node, index) => {
      let replacement = Array.isArray(value) ? value[index] : value;
      if (replacement === undefined) return;
      node.innerHTML = replacement;
    });
  }

  document.querySelectorAll("nav a").forEach((node, index) => {
    node.innerHTML = dict.nav[index];
  });

  const button = document.querySelector("#languageToggle");
  button.innerHTML = lang === "ja" ? '日本語 <span>/</span> EN' : 'EN <span>/</span> 日本語';
  button.setAttribute("aria-label", lang === "ja" ? "英語に切り替える" : "Switch to Japanese");
  localStorage.setItem("serendipity-language", lang);
}

const savedLanguage = localStorage.getItem("serendipity-language") || "en";
applyLanguage(savedLanguage);

document.querySelector("#languageToggle").addEventListener("click", () => {
  const next = document.documentElement.lang === "ja" ? "en" : "ja";
  applyLanguage(next);
});

